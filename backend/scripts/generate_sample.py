"""Generate SAMPLE KPI data for Weekly Review Copilot.

NOTE: This is synthetic sample data. The brands, numbers and trends are made
up for demonstration and are not real business results.

Run from the backend folder:
    python scripts/generate_sample.py

Writes:
    data/sample_kpis.csv   (8 weeks x 3 brands x 4 metrics = 96 rows)
    data/README.txt        (a note saying the data is sample data)
"""

import csv
import random
from datetime import date, timedelta
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BACKEND_DIR / "data"
CSV_PATH = DATA_DIR / "sample_kpis.csv"
NOTE_PATH = DATA_DIR / "README.txt"

SEED = 7
WEEKS = 8
FIRST_WEEK = date(2026, 9, 21)  # a Monday; the 8th week starts 2026-11-09
METRICS = ["leads", "revenue_inr", "enrollments", "conversion_rate"]

NOTE = (
    "SAMPLE DATA\n"
    "sample_kpis.csv is synthetic data generated by scripts/generate_sample.py.\n"
    "The brands, numbers and trends are made up for demonstration only and are\n"
    "not real business results.\n"
)

# The *_att lists hold the planned attainment (actual / target) of each driver
# for each of the 8 weeks, where 1.0 is exactly on target. Enrollments and
# revenue are derived from these drivers so the four metrics stay consistent.
BRANDS = {
    "SkillfyAI": {  # strong and growing, with a conversion dip in the latest week
        "leads_target": 1400,
        "weekly_growth": 0.015,
        "conv_target": 6.0,
        "ticket": 18000,
        "leads_att": [0.97, 1.00, 1.03, 1.05, 1.04, 1.08, 1.06, 1.10],
        "conv_att": [0.95, 0.98, 1.00, 1.02, 1.03, 1.01, 1.05, 0.96],
        "ticket_att": [1.00, 0.99, 1.01, 1.00, 1.02, 1.01, 1.00, 1.02],
    },
    "VSH7 Technologies": {  # steadily slipping off target
        "leads_target": 380,
        "weekly_growth": 0.01,
        "conv_target": 4.5,
        "ticket": 120000,
        "leads_att": [1.02, 1.00, 0.98, 0.95, 0.92, 0.89, 0.86, 0.84],
        "conv_att": [1.00, 0.98, 0.97, 0.94, 0.92, 0.89, 0.87, 0.85],
        "ticket_att": [1.00, 1.00, 0.99, 0.98, 0.97, 0.95, 0.94, 0.93],
    },
    "SharmaJEE": {  # more leads each week, but conversion keeps falling
        "leads_target": 2600,
        "weekly_growth": 0.02,
        "conv_target": 5.5,
        "ticket": 45000,
        "leads_att": [0.92, 0.95, 0.98, 1.02, 1.05, 1.07, 1.09, 1.12],
        "conv_att": [0.82, 0.80, 0.83, 0.84, 0.81, 0.79, 0.77, 0.76],
        "ticket_att": [1.00, 1.02, 1.01, 1.00, 1.03, 1.01, 1.02, 1.00],
    },
}


def jitter(rng: random.Random) -> float:
    return 1 + rng.uniform(-0.01, 0.01)


def build_rows() -> list[dict]:
    rng = random.Random(SEED)
    rows: list[dict] = []
    for i in range(WEEKS):
        week = (FIRST_WEEK + timedelta(weeks=i)).isoformat()
        for brand, cfg in BRANDS.items():
            leads_t = round(cfg["leads_target"] * (1 + cfg["weekly_growth"]) ** i)
            conv_t = cfg["conv_target"]
            enroll_t = round(leads_t * conv_t / 100)
            revenue_t = int(round(leads_t * conv_t / 100 * cfg["ticket"], -3))

            leads_a = round(leads_t * cfg["leads_att"][i] * jitter(rng))
            planned_conv = conv_t * cfg["conv_att"][i] * jitter(rng)
            enroll_a = round(leads_a * planned_conv / 100)
            conv_a = round(enroll_a / leads_a * 100, 2)
            revenue_a = int(
                round(enroll_a * cfg["ticket"] * cfg["ticket_att"][i] * jitter(rng), -3)
            )

            values = {
                "leads": (leads_a, leads_t),
                "revenue_inr": (revenue_a, revenue_t),
                "enrollments": (enroll_a, enroll_t),
                "conversion_rate": (conv_a, conv_t),
            }
            for metric in METRICS:
                actual, target = values[metric]
                rows.append(
                    {
                        "week_start": week,
                        "brand": brand,
                        "metric": metric,
                        "actual": actual,
                        "target": target,
                    }
                )
    return rows


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()

    with CSV_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f, fieldnames=["week_start", "brand", "metric", "actual", "target"]
        )
        writer.writeheader()
        writer.writerows(rows)
    NOTE_PATH.write_text(NOTE, encoding="utf-8")

    latest = max(r["week_start"] for r in rows)
    print(f"Wrote {len(rows)} rows to {CSV_PATH}")
    print("NOTE: this is sample data, not real business results.")
    print(f"\nLatest week ({latest}), actual as % of target:")
    for r in rows:
        if r["week_start"] == latest:
            pct = r["actual"] / r["target"] * 100
            print(f"  {r['brand']:<18} {r['metric']:<16} {pct:6.1f}%")


if __name__ == "__main__":
    main()